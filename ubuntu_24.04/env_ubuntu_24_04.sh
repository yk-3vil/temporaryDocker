#!/usr/bin/env bash
#
################################################################################
# Script Description
# Overview:
#   Ubuntu 24.04 環境用の環境変数定義ファイル
# Usage:
#   source "${PROJECT_ROOT}/ubuntu_24.04/env_ubuntu_24_04.sh"
# Arguments:
#   なし
# Returns:
#   なし
# Notes:
#   各スクリプトで source することで変数の一元管理を実現
# Example:
#   source "${PROJECT_ROOT}/ubuntu_24.04/env_ubuntu_24_04.sh"
################################################################################

# 厳格モードの設定
set -Eeuo pipefail
IFS=$'\n\t'

# ==============================================================================
# 基本変数
# ==============================================================================

# バージョン（ドット区切り）
readonly ENV_VERSION="24.04"

# ベース名（環境の種類）
readonly ENV_BASE_NAME="ubuntu"

# ==============================================================================
# Docker リソース名（バージョンはドット区切り）
# ==============================================================================

# Docker イメージ名
readonly ENV_IMAGE_NAME="ubuntu_24.04:latest"

# Docker コンテナ名
readonly ENV_CONTAINER_NAME="ubuntu_24.04_container"

# ==============================================================================
# マウント設定
# ==============================================================================

# コンテナ内のマウントターゲットパス
readonly ENV_MOUNT_TARGET="/workspace"

# ==============================================================================
# イメージ作成日時（ISO 8601形式）
# ==============================================================================

# 現在時刻をISO 8601形式で取得（UTC）
readonly ENV_CREATED_DATE="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"

################################################################################
# Function Description:
#   ドット区切りをアンダースコア区切りに変換
# Overview:
#   バージョン文字列のドット(.)をアンダースコア(_)に変換
# Arguments:
#   $1: ドット区切りの文字列 (例: "24.04")
# Returns/Outputs:
#   アンダースコア区切りの文字列を標準出力へ出力 (例: "24_04")
# Notes:
#   bash の文字列置換機能を使用
# Example:
#   version_dot_to_underscore "24.04"  # "24_04" を出力
################################################################################
function version_dot_to_underscore() {
  local version="$1"
  echo "${version//./_}"
}

################################################################################
# Function Description:
#   アンダースコア区切りをドット区切りに変換
# Overview:
#   バージョン文字列のアンダースコア(_)をドット(.)に変換
# Arguments:
#   $1: アンダースコア区切りの文字列 (例: "24_04")
# Returns/Outputs:
#   ドット区切りの文字列を標準出力へ出力 (例: "24.04")
# Notes:
#   bash の文字列置換機能を使用
# Example:
#   version_underscore_to_dot "24_04"  # "24.04" を出力
################################################################################
function version_underscore_to_dot() {
  local version="$1"
  echo "${version//_/.}"
}

# ==============================================================================
# エクスポート（他のシェルスクリプトで使用可能にする）
# ==============================================================================

export ENV_VERSION
export ENV_BASE_NAME
export ENV_IMAGE_NAME
export ENV_CONTAINER_NAME
export ENV_MOUNT_TARGET
export ENV_CREATED_DATE
