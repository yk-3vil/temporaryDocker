#!/usr/bin/env bash
#
################################################################################
# Script Description
# Overview:
#   cimg/openjdk 21.0.9 環境用の環境変数定義ファイル
#   各スクリプトでこのファイルを source することで、変数の一元管理を実現
# Usage:
#   source "${PROJECT_ROOT}/cimg_openjdk_21.0.9/env_cimg_openjdk_21_0_9.sh"
# Arguments:
#   なし
# Returns:
#   なし（変数定義とエクスポートのみ）
# Notes:
#   厳格モード（set -Eeuo pipefail）を適用
#   バージョン変換ヘルパー関数を提供（ドット↔アンダースコア）
# Example:
#   source "${PROJECT_ROOT}/cimg_openjdk_21.0.9/env_cimg_openjdk_21_0_9.sh"
#   echo "イメージ名: ${ENV_IMAGE_NAME}"
#   echo "コンテナ名: ${ENV_CONTAINER_NAME}"
################################################################################

# 厳格モードの設定
set -Eeuo pipefail
IFS=$'\n\t'

# ====================================================================================================================
# 基本変数
# ====================================================================================================================

# バージョン（ドット区切り）
readonly ENV_VERSION="21.0.9"

# ベース名（環境の種類）
readonly ENV_BASE_NAME="cimg_openjdk"

# ====================================================================================================================
# Docker リソース名（バージョンはドット区切り）
# ====================================================================================================================

# Docker イメージ名
readonly ENV_IMAGE_NAME="cimg_openjdk_21.0.9:latest"

# Docker コンテナ名
readonly ENV_CONTAINER_NAME="cimg_openjdk_21.0.9_container"

# ====================================================================================================================
# マウント設定
# ====================================================================================================================

# コンテナ内のマウントターゲットパス
readonly ENV_MOUNT_TARGET="/home/circleci/project"

# ====================================================================================================================
# イメージ作成日時（ISO 8601形式）
# ====================================================================================================================

# 現在時刻をISO 8601形式で取得（UTC）
readonly ENV_CREATED_DATE="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"

################################################################################
# Function Description:
#   ドット区切りをアンダースコア区切りに変換
# Overview:
#   バージョン文字列のドットをアンダースコアに置換
# Arguments:
#   $1: ドット区切りの文字列（例: "21.0.9"）
# Returns/Outputs:
#   アンダースコア区切りの文字列を標準出力（例: "21_0_9"）
# Notes:
#   bash の文字列置換機能（${var//pattern/replacement}）を使用
# Example:
#   version_dot_to_underscore "21.0.9"  # 出力: 21_0_9
################################################################################
function version_dot_to_underscore() {
  local version="$1"
  echo "${version//./_}"
}

################################################################################
# Function Description:
#   アンダースコア区切りをドット区切りに変換
# Overview:
#   バージョン文字列のアンダースコアをドットに置換
# Arguments:
#   $1: アンダースコア区切りの文字列（例: "21_0_9"）
# Returns/Outputs:
#   ドット区切りの文字列を標準出力（例: "21.0.9"）
# Notes:
#   bash の文字列置換機能（${var//pattern/replacement}）を使用
# Example:
#   version_underscore_to_dot "21_0_9"  # 出力: 21.0.9
################################################################################
function version_underscore_to_dot() {
  local version="$1"
  echo "${version//_/.}"
}

# ==============================================================================
# エクスポート（他のシェルスクリプトで使用可能にする）
# ==============================================================================

export ENV_VERSION
export ENV_BASE_NAME
export ENV_IMAGE_NAME
export ENV_CONTAINER_NAME
export ENV_MOUNT_TARGET
export ENV_CREATED_DATE
